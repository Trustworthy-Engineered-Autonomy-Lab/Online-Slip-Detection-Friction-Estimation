import numpy as np

def mae(pred, true):
    return np.mean(np.abs(pred - true))

def mre(pred, true):
    return np.mean(np.abs(pred - true) / np.abs(true))

tile = np.array(tile)
cardboard = np.array(cardboard)
acrylic = np.array(acrylic)
gt_acrylic = np.array(gt_acrylic)


